// Writes an FM1B bank as a C array for the firmware (fm1_open/app/fm1b_bank_data.inc), one preset or all of them.
//   node make_bank_c.js <in.sf2> [preset number | all] [rate] [out.inc]
// The file is included by fm1_open/app/fm1b_bank.c when it exists and is not committed (it holds the sounds of the sf2).
const fs = require('fs');
const html = fs.readFileSync(__dirname + '/index.html', 'utf8');
eval(html.match(/<script id="core">([\s\S]*?)<\/script>/)[1] + '\nglobalThis.api = { parseSf2, buildBank, writeFm1 };');
const [inPath, which = '0', rateArg = '32000', outPath = __dirname + '/fm1_open/app/fm1b_bank_data.inc'] = process.argv.slice(2);
const b = fs.readFileSync(inPath);
const sf = api.parseSf2(b.buffer.slice(b.byteOffset, b.byteOffset + b.length));
const idx = which === 'all' ? -2 : sf.presets.findIndex(p => p.bank === 0 && p.preset === +which);
if (idx === -1) throw new Error('no such melodic preset');
const bank = api.buildBank(sf, idx, { rate: +rateArg, sea: true });
const bin = api.writeFm1(bank);
let text = '/* Generated by make_bank_c.js from ' + require('path').basename(inPath) + ', preset ' + which + '. Do not edit. */\n' +
  'static const uint8_t fm1b_bank_data[' + bin.length + '] __attribute__((aligned(4))) = {\n';
for (let i = 0; i < bin.length; i += 24) text += Array.from(bin.subarray(i, i + 24)).join(',') + ',\n';
fs.writeFileSync(outPath, text + '};\n');
console.log('wrote', outPath, bin.length, 'bytes,', bank.presets.length, 'presets,', bank.zones.length, 'zones');
