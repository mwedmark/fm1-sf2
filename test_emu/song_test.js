// Helpers to test the MIDI file player in fm1-emu (start_emu.ps1 copies this file and fm1_song.js into emu/). In the page's console:
//   await import('/song_test.js')            then
//   await songUpload('/never.fm1s')          a song made by: node fm1_song.js <file.mid> emu\never.fm1s
//   songPlay(), songStop(), press(12)        the upload's play and stop commands, a panel button (12 PLAY, 13 REC, 8 HOME)
//   screen()                                 the program page's text, read from window.__lcd (works while the page is hidden)
// The emulator takes MIDI in at its DIN jack, at about 3 KB/s: the frames go in 30-byte pieces 11 ms apart (60 KB: about 35 s).
await import('/fm1_song.js');
const S = window.Fm1Song;
const wait = (ms) => new Promise((r) => setTimeout(r, ms));

async function sendPaced(frame) {
  for (let i = 0; i < frame.length; i += 30) { window.__midi(frame.subarray(i, i + 30)); await wait(11); }
  await wait(20);
}
window.songUpload = async (url) => {
  const song = new Uint8Array(await (await fetch(url)).arrayBuffer());
  for (const f of S.songFrames(song)) await sendPaced(f);
  await wait(200);
  return song.length;
};
window.songPlay = () => sendPaced(S.playFrame());
window.songStop = () => sendPaced(S.stopFrame());
window.press = async (id) => { window.__key(id, true); await wait(80); window.__key(id, false); await wait(150); };

