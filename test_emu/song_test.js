// One line of text at y, scale 1 or 2; the background is the line's last pixel
window.lcdLine = (y, s) => {
  const l = window.__lcd, bg = l[y * 240 + 239];
  let out = '';
  for (let c = 0; (c + 1) * 6 * s <= 240; c++) {
    const g = [];
    for (let col = 0; col < 5; col++) {
      let b = 0;
      for (let r = 0; r < 7; r++) if (l[(y + r * s) * 240 + c * 6 * s + col * s] !== bg) b |= 1 << r;
      g.push(b);
    }
    out += shapes.get(g.join()) ?? '?';
  }
  return out.trimEnd();
};
